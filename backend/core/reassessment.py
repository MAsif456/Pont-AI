"""Bounded impact assessment for incoming clinical updates.

A single structured LLM call -- not agentic, no tools. It compares what changed
against the patient's existing assessment and decides whether discharge readiness
is affected and whether a full re-run is warranted. It never re-runs anything
itself; the caller decides what to do with the result.
"""

import json

from core.json_utils import generate_json
from core.llm.base import LLMClient
from models.context import ClinicalUpdate
from models.reassessment import ImpactAssessment

_PROMPT = """TASK: ASSESS_UPDATE_IMPACT
You are a social-care reassessment assistant. A patient already has an assessment \
and recommendations. New clinical updates have arrived from the hospital side. \
Decide whether they change the picture -- do not restate the whole assessment.

New clinical updates and/or notes from the ward or family have arrived. Decide \
whether they change the picture -- do not restate the whole assessment.

Return JSON ONLY (no prose, no code fences):
{{"summary": string, "affects_discharge": boolean, "discharge_impact": string, "recommend_rerun": boolean, "recommendation_note": string}}

- summary: a plain-language description of what changed.
- affects_discharge: true if the change affects discharge readiness.
- discharge_impact: how it affects discharge readiness, or that it does not.
- recommend_rerun: true only if the existing recommendations should be regenerated by re-running the full assessment.
- recommendation_note: whether the existing recommendations still hold, or should be re-run.

INPUT:
{payload}"""


def assess_update_impact(
    llm: LLMClient,
    previous_assessment: dict,
    updates: list[ClinicalUpdate],
    interaction_notes: list[str] | None = None,
) -> ImpactAssessment:
    """Assess whether the clinical updates and/or notes change the existing picture."""
    payload = json.dumps(
        {
            "previous_assessment": previous_assessment,
            "clinical_updates": [update.model_dump() for update in updates],
            "interaction_notes": interaction_notes or [],
        }
    )
    result = generate_json(llm, _PROMPT.format(payload=payload))
    result = result if isinstance(result, dict) else {}
    return ImpactAssessment(
        summary=str(result.get("summary", "")),
        affects_discharge=bool(result.get("affects_discharge", False)),
        discharge_impact=str(result.get("discharge_impact", "")),
        recommend_rerun=bool(result.get("recommend_rerun", False)),
        recommendation_note=str(result.get("recommendation_note", "")),
    )
